for (const f of V3_FAMILIES) t(`| ${f.icon} ${f.name} | ${esc(f.seat)} | ${f.cc} | ${f.trait.name} | ${f.atk.name} | ${f.def.name} | ${f.spc.name} | ${f.ult.name} |`);
