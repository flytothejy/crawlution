for (const f of V3_FAMILIES) {
  p(`## ${f.icon} ${f.name}`);
  p(`${f.seat}. 맡는 제어: ${f.cc}. 진화: ${f.stages.join(' → ')}.${f.merged ? ` (${f.merged})` : ''}`);
  p(`**계열 특성 · ${f.trait.name}** — ${f.trait.desc} 연출: ${f.trait.fx} (비슷한 것: ${f.trait.ref})`);
  t('| 칸 | 기술 | 유형 | 하는 일 | 각성 | 이펙트·모션 | 비슷한 기술 |');
  t('|---|---|---|---|---|---|---|');
  for (const sl of ['atk', 'def', 'spc', 'ult'] as V3Slot[]) {
    const k = f[sl];
    t(`| ${SLOT_NAME[sl]} | ${k.icon} ${k.name}${k.from ? ` (2판 ${k.from})` : ' (새)'} | ${k.type}${k.cd ? ` · ${k.cd}초` : ''} | ${esc(k.desc)} | ${k.awake ?? '—'} | ${esc(k.fx)} | ${esc(k.ref)} |`);
  }
  p(`모습: ${f.look} 공통 연출: ${f.motion}`);
  p(`강함: ${f.strong} 약함: ${f.weak}`);
  t('| 종 | 바뀐 칸 → 종 기술 | 종 기술이 하는 일 | 본능 | 모습 | 연출 |');
  t('|---|---|---|---|---|---|');
  for (const id of f.species) {
    const s = V3_BY_ID.get(id)!;
    const k = s.skill;
    t(`| ${s.name}${s.base ? ' (대표)' : ''}${s.isNew ? ' 🆕' : ''} | ${s.base ? '— 그대로' : `${SLOT_NAME[s.swap!]} → ${k!.icon} ${k!.name}`} | ${k ? esc(k.desc + ' 연출: ' + k.fx) : '—'} | **${s.instinct.name}**: ${esc(s.instinct.desc)} | ${esc(s.gfx)} | ${esc(s.theme.tag)} |`);
  }
}
