p('## 새로 만든 연출');
p('새 머리 모양 3개(개미 하트 머리, 나비 털 머리+대롱 입, 노래기 둥근 머리), 나비 날개 5무늬(호랑·제왕·올빼미·모르포·나방, 앞날개+뒷날개를 위에서 본 모습, 접었다 펴는 날갯짓), 검은 날개(물잠자리), 입자 4개(개미, 인분 반짝이, 독털, 나비), 새 이펙트 18개(독턱 X자, 몸 고리, 소용돌이, 개미산, 땅굴, 개미 부르기, 개미 강물, 잎 방패, 불개미 둥지, 진동, 진흙 항아리, 인분 구름, 팔랑 잔상, 매혹 꽃가루, 나비 떼 폭풍, 눈알 무늬, 푸른 섬광, 독털). 맞은 쪽 반응으로 혼란(갈지자 걸음+반짝이), 매혹(나에게 걸어옴+꽃잎), 가려움을 보여 준다.');
