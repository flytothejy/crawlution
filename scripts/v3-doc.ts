const p = (s = '') => out.push('', s, '');
const t = (s: string) => out.push(s);
const esc = (s: string) => s.replace(/\|/g, '/');
p('# 3판 40종 설계');
p('2026-11-25 · 8계열 × 5종. 계열 특성(늘) + 공격(Lv1) · 방어(Lv3) · 특수(Lv5) + 필살기(게이지), Lv10 각성. 종마다 한 칸을 종 기술로 바꾸고 본능 하나를 단다. 이 표는 도감(크롤루션 도감 → 🆕 3판 40종)에서 모습과 이펙트를 직접 재생해 볼 수 있다. 새 기술은 아직 이펙트·반응 연출만 있고 피해 계산은 구현할 때 넣는다.');
