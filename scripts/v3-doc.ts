p('혼란 세기(지금 안: 조작 방향이 조금 흔들리고 기술 조준이 빗나감 — 약하게), 웅크리기 버튼을 남길지, 아레나 보스(왕지네 → 다른 것), 개미 일개미 행렬의 피해(마리당 물기 20%)가 개미를 너무 세게 만들지 시뮬레이션으로 확인.');
